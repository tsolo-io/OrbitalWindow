"""Image builds, run one at a time by a background worker. Progress is written to ``builds.log``.

- **base**: ``deploy/image/`` on top of a LinuxServer webtop tag → ``ow-desktop:<tag>``, then the
  image's apt package names are stored in ``pkg_index``.
- **user**: a generated context ``FROM ow-desktop:<tag>`` with the user's add-ons and packages →
  ``ow-user-<name>:latest``. Docker only tags on success, so a failed build keeps the last good one.
"""

import logging
import queue
import re
import shlex
import shutil
import tempfile
import threading
import time
from collections.abc import Callable, Iterator
from pathlib import Path
from typing import Any

import docker

from .db import Database
from .software import Software, UserPlan, user_image_ref
from .users import get_user

log = logging.getLogger(__name__)

TAG_RE = re.compile(r"^[a-z0-9][a-z0-9._-]{0,63}$")
LOG_FLUSH_SECONDS = 1.0
MAX_LOG_CHARS = 400_000
APT_INSTALL = "DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends"
APT_CLEAN = "rm -rf /var/lib/apt/lists/*"
STEP = "/usr/local/sbin/ow-step"
# Wraps long build steps. It prints a line every minute so the build stream through the socket
# proxy (which drops connections idle for 10 minutes) never goes quiet, and users see progress.
STEP_SCRIPT = """#!/bin/sh
( while sleep 60; do echo "... still working ($(date +%H:%M))"; done ) &
ticker=$!
"$@"
status=$?
kill "$ticker" 2>/dev/null
exit "$status"
"""


def _step(cmd: str) -> str:
    return f"RUN {STEP} sh -euc {shlex.quote(cmd)}"


def desktop_image_ref(base_tag: str) -> str:
    return f"ow-desktop:{base_tag}"


def user_dockerfile(plan: UserPlan) -> str:
    """The per-user Dockerfile. Add-ons come first in key order, so users with the same add-ons
    share cached layers; the user's own packages come last."""
    lines = [
        "# Generated by OrbitalWindow. Do not edit.",
        f"FROM {plan.base_ref}",
        'SHELL ["/bin/sh", "-eu", "-c"]',
        f"COPY ow-step {STEP}",
    ]
    for addon in plan.addons:
        spec = addon.spec
        folder = f"/opt/ow/addons/{spec.key}"
        lines.append(f"# add-on: {spec.key}")
        lines.append(f"COPY addons/{spec.key}/ {folder}/")
        if spec.apt:
            lines.append(
                _step(f"apt-get update && {APT_INSTALL} {shlex.join(spec.apt)} && {APT_CLEAN}")
            )
        if spec.script:
            lines.append(_step(f"cd {folder} && sh ./{spec.script} && {APT_CLEAN}"))
        if spec.launchers:
            lines.append(
                "RUN install -m 644 "
                + " ".join(f"{folder}/{name}" for name in spec.launchers)
                + " /usr/share/applications/"
            )
    if plan.packages:
        lines.append("# the user's own packages")
        lines.append(
            _step(f"apt-get update && {APT_INSTALL} {shlex.join(plan.packages)} && {APT_CLEAN}")
        )
    lines.append(f'LABEL ow.managed="true" ow.role="user-image" ow.user="{plan.name}"')
    return "\n".join(lines) + "\n"


class Builder:
    def __init__(
        self,
        client: docker.DockerClient,
        db: Database,
        software: Software,
        image_context: Path,
        webtop_repo: str,
    ) -> None:
        self._client = client
        self._db = db
        self._software = software
        self._context = image_context
        self._repo = webtop_repo
        self._queue: queue.Queue[int] = queue.Queue()
        self._thread: threading.Thread | None = None
        self._stop = threading.Event()
        # Called after a base image is rebuilt, with its image id (to queue user rebuilds).
        self.on_base_ready: Callable[[int], None] | None = None

    def start(self) -> None:
        # Builds interrupted by a restart are marked failed; they can be started again.
        self._db.execute(
            "UPDATE builds SET status = 'failed', finished_at = now(), "
            "log = log || '\n[interrupted by a service restart]' "
            "WHERE status IN ('queued', 'running')"
        )
        self._db.execute(
            "UPDATE images SET status = CASE WHEN built_at IS NULL THEN 'failed' ELSE 'ready' END "
            "WHERE status = 'building'"
        )
        self._db.execute(
            "UPDATE user_image SET status = CASE WHEN built_at IS NULL THEN 'failed' "
            "ELSE 'ready' END WHERE status IN ('queued', 'building')"
        )
        self._thread = threading.Thread(target=self._run, name="ow-builder", daemon=True)
        self._thread.start()

    def stop(self) -> None:
        self._stop.set()
        self._queue.put(0)

    # --- queueing ----------------------------------------------------------------------------

    def queue_base(self, image_id: int) -> int:
        if self._db.one("SELECT id FROM images WHERE id = ?", [image_id]) is None:
            raise ValueError(f"unknown image {image_id}")
        with self._db.transaction():
            self._db.execute("UPDATE images SET status = 'building' WHERE id = ?", [image_id])
            build_id = self._db.scalar(
                "INSERT INTO builds (kind, target, status) "
                "VALUES ('base', ?, 'queued') RETURNING id",
                [str(image_id)],
            )
        self._queue.put(build_id)
        return build_id

    def queue_user(self, user_id: int) -> int | None:
        """Queue a per-user build unless one is already waiting. Returns the build id."""
        with self._db.transaction():
            waiting = self._db.scalar(
                "SELECT id FROM builds WHERE kind = 'user' AND target = ? AND status = 'queued'",
                [str(user_id)],
            )
            if waiting:
                return waiting
            build_id = self._db.scalar(
                "INSERT INTO builds (kind, target, status) "
                "VALUES ('user', ?, 'queued') RETURNING id",
                [str(user_id)],
            )
            self._db.execute(
                "INSERT INTO user_image (user_id, image_ref, status, build_id) "
                "VALUES (?, '', 'queued', ?) ON CONFLICT (user_id) DO UPDATE "
                "SET status = 'queued', build_id = excluded.build_id",
                [user_id, build_id],
            )
        self._queue.put(build_id)
        return build_id

    def latest_build(self, kind: str, target: int) -> dict[str, Any] | None:
        return self._db.one(
            "SELECT * FROM builds WHERE kind = ? AND target = ? ORDER BY id DESC LIMIT 1",
            [kind, str(target)],
        )

    # --- worker ------------------------------------------------------------------------------

    def _run(self) -> None:
        while not self._stop.is_set():
            build_id = self._queue.get()
            if self._stop.is_set():
                return
            try:
                build = self._db.one("SELECT * FROM builds WHERE id = ?", [build_id])
                if build is None or build["status"] != "queued":
                    continue
                if build["kind"] == "base":
                    self._build_base(build_id, int(build["target"]))
                else:
                    self._build_user(build_id, int(build["target"]))
            except Exception:
                log.exception("build %s crashed", build_id)

    def _mark_running(self, build_id: int) -> None:
        self._db.execute(
            "UPDATE builds SET status = 'running', started_at = now() WHERE id = ?", [build_id]
        )

    def _finish(self, build_id: int, ok: bool) -> None:
        self._db.execute(
            "UPDATE builds SET status = ?, finished_at = now() WHERE id = ?",
            ["ok" if ok else "failed", build_id],
        )

    def _stream(self, writer: _LogWriter, chunks: Iterator[dict[str, Any]]) -> None:
        for chunk in chunks:
            if "stream" in chunk:
                writer.write(chunk["stream"])
            elif "status" in chunk:
                # Pull progress is noisy; keep only the lines without a progress bar.
                if "progress" not in chunk:
                    writer.write(f"{chunk.get('id', '')} {chunk['status']}\n".lstrip())
            elif "error" in chunk:
                writer.write(f"ERROR: {chunk['error']}\n")
                raise RuntimeError(chunk["error"])

    def _build_base(self, build_id: int, image_id: int) -> None:
        image = self._db.one("SELECT * FROM images WHERE id = ?", [image_id])
        if image is None:
            self._finish(build_id, False)
            return
        self._mark_running(build_id)
        writer = _LogWriter(self._db, build_id)
        ok = False
        try:
            base = f"{self._repo}:{image['base_tag']}"
            writer.write(f"Building {image['image_ref']} from {base}\n")
            self._stream(
                writer,
                self._client.api.build(
                    path=str(self._context),
                    tag=image["image_ref"],
                    buildargs={"BASE_IMAGE": base},
                    pull=True,
                    rm=True,
                    forcerm=True,
                    decode=True,
                    labels={"ow.managed": "true", "ow.role": "desktop-image"},
                ),
            )
            docker_id = self._client.images.get(image["image_ref"]).id
            writer.write("\nReading the package list of the new image…\n")
            count = self._index_packages(image_id, image["image_ref"])
            writer.write(f"{count} packages available.\n")
            self._db.execute(
                "UPDATE images SET status = 'ready', built_at = now(), docker_id = ? WHERE id = ?",
                [docker_id, image_id],
            )
            ok = True
        except Exception as e:
            writer.write(f"\nBuild failed: {e}\n")
            # Keep a previously good image usable.
            self._db.execute(
                "UPDATE images SET status = CASE WHEN built_at IS NULL THEN 'failed' "
                "ELSE 'ready' END WHERE id = ?",
                [image_id],
            )
        finally:
            writer.flush()
            self._finish(build_id, ok)
        if ok:
            self._prune()
            if self.on_base_ready:
                self.on_base_ready(image_id)

    def _index_packages(self, image_id: int, image_ref: str) -> int:
        """Fill pkg_index from ``apt-cache pkgnames`` (the image ships without apt lists)."""
        out = self._client.containers.run(
            image_ref,
            ["-c", "apt-get update -qq >/dev/null 2>&1 && apt-cache pkgnames"],
            entrypoint="/bin/sh",
            user="root",
            remove=True,
            stdout=True,
            stderr=False,
            labels={"ow.managed": "true", "ow.role": "helper"},
        )
        names = sorted({n for n in out.decode().split() if n})
        if not names:
            raise RuntimeError("the package list is empty (is the network reachable?)")
        with self._db.transaction():
            self._db.execute("DELETE FROM pkg_index WHERE image_id = ?", [image_id])
            self._db.execute(
                "INSERT INTO pkg_index SELECT ?, unnest(?::VARCHAR[])", [image_id, names]
            )
        return len(names)

    def _build_user(self, build_id: int, user_id: int) -> None:
        user = get_user(self._db, user_id)
        if user is None:
            self._finish(build_id, False)
            return
        self._mark_running(build_id)
        self._db.execute("UPDATE user_image SET status = 'building' WHERE user_id = ?", [user_id])
        writer = _LogWriter(self._db, build_id)
        ok = False
        plan: UserPlan | None = None
        try:
            plan = self._software.plan(user)
            if plan.hash is None:
                writer.write("No add-ons or packages need an image: using the desktop as is.\n")
                self._remove_user_image(user["name"])
                self._db.execute("DELETE FROM user_image WHERE user_id = ?", [user_id])
                ok = True
                return
            ref = user_image_ref(user["name"])
            labels = ", ".join(a.key for a in plan.addons) or "none"
            writer.write(f"Building {ref} from {plan.base_ref}\n")
            writer.write(f"Add-ons: {labels}\nPackages: {' '.join(plan.packages) or 'none'}\n\n")
            with tempfile.TemporaryDirectory(prefix="ow-build-") as tmp:
                ctx = Path(tmp)
                (ctx / "addons").mkdir()
                for addon in plan.addons:
                    shutil.copytree(addon.path, ctx / "addons" / addon.key)
                (ctx / "Dockerfile").write_text(user_dockerfile(plan))
                (ctx / "ow-step").write_text(STEP_SCRIPT)
                (ctx / "ow-step").chmod(0o755)  # COPY keeps the mode (--chmod needs BuildKit)
                self._stream(
                    writer,
                    self._client.api.build(
                        path=str(ctx), tag=ref, rm=True, forcerm=True, decode=True, pull=False
                    ),
                )
            self._db.execute(
                "UPDATE user_image SET image_ref = ?, built_from_image_id = ?, pkg_hash = ?, "
                "built_at = now() WHERE user_id = ?",
                [ref, plan.image_id, plan.hash, user_id],
            )
            writer.write("\nDone. Restart your desktop to use the new software.\n")
            ok = True
        except Exception as e:
            writer.write(f"\nBuild failed: {e}\n")
        finally:
            writer.flush()
            self._finish(build_id, ok)
            self._db.execute(
                "UPDATE user_image SET status = CASE WHEN ? THEN 'ready' "
                "WHEN built_at IS NULL THEN 'failed' ELSE 'ready' END WHERE user_id = ?",
                [ok, user_id],
            )
        if ok:
            self._prune()

    def _remove_user_image(self, name: str) -> None:
        try:
            self._client.images.remove(user_image_ref(name), noprune=False)
        except docker.errors.ImageNotFound:
            pass
        except docker.errors.APIError as e:  # still used by a running desktop
            log.info("keeping %s for now: %s", user_image_ref(name), e.explanation)

    def _prune(self) -> None:
        """Remove superseded (dangling) images we built."""
        try:
            self._client.images.prune(filters={"dangling": True, "label": "ow.managed=true"})
        except docker.errors.APIError as e:
            log.warning("image prune failed: %s", e)


class _LogWriter:
    """Batches log lines into the DB so a chatty build doesn't write on every line."""

    def __init__(self, db: Database, build_id: int) -> None:
        self._db = db
        self._id = build_id
        self._buf: list[str] = []
        self._size = 0
        self._last = time.monotonic()

    def write(self, text: str) -> None:
        if self._size > MAX_LOG_CHARS:
            return
        self._buf.append(text)
        self._size += len(text)
        if self._size > MAX_LOG_CHARS:
            self._buf.append("\n[log truncated]\n")
        if time.monotonic() - self._last >= LOG_FLUSH_SECONDS:
            self.flush()

    def flush(self) -> None:
        if self._buf:
            self._db.execute(
                "UPDATE builds SET log = log || ? WHERE id = ?", ["".join(self._buf), self._id]
            )
            self._buf.clear()
        self._last = time.monotonic()
