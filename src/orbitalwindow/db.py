def open_database(settings: Settings) -> Database:
    """Make OrbitalWindow's database on the server if needed, then connect to it.

    Args:
        settings: Application settings (the server and its superuser).

    Returns:
        The connected database, migrated.
    """
    if not settings.database_url_override:
        pg.ensure_database(settings, settings.db_name)
    return Database(settings.database_url())


class _NumericLoader(Loader):
    """Load ``numeric`` (``sum()`` of integers, ``round()``) as int when whole, else float."""

    def load(self, data: bytes) -> int | float:
        """Convert one value.

        Args:
            data: The value as PostgreSQL sends it in text form.

        Returns:
            An int for a whole number, otherwise a float.
        """
        value = Decimal(bytes(data).decode())
        return int(value) if value == value.to_integral_value() else float(value)


@functools.lru_cache(maxsize=1024)
def to_psycopg(sql: str) -> str:
    """Turn ``?`` placeholders into ``%s`` and escape ``%``, outside quoted text.

    Args:
        sql: SQL with ``?`` placeholders.

    Returns:
        The same SQL for psycopg.
    """
    out = []
    quote = ""
    for char in sql:
        if quote:
            if char == quote:
                quote = ""
            out.append("%%" if char == "%" else char)
        elif char in "'\"":
            quote = char
            out.append(char)
        elif char == "?":
            out.append("%s")
        elif char == "%":
            out.append("%%")
        else:
            out.append(char)
    return "".join(out)


class Database:
    def __init__(self, url: str) -> None:
        """Connect to the database and apply pending migrations.

        Args:
            url: PostgreSQL connection URL (``postgresql://user:password@host/name``).
        """
        self._url = url
        self._lock = threading.RLock()
        self._depth = 0
        self._con = self._connect()
        self._migrate()

    def _connect(self) -> psycopg.Connection:
        """Open a connection: autocommit (transactions are explicit), dict rows, UTC.

        Returns:
            The connection.
        """
        con = psycopg.connect(self._url, autocommit=True, row_factory=dict_row)
        # Timestamps are stored as naive UTC (TIMESTAMP); now() is read in UTC too.
        con.execute("SET TIME ZONE 'UTC'")
        con.adapters.register_loader("numeric", _NumericLoader)
        return con

    def close(self) -> None:
        """Close the connection."""
        with self._lock:
            self._con.close()

    def _migrate(self) -> None:
        """Apply every migration in ``MIGRATIONS`` newer than the recorded schema version."""
        with self._lock:
            self._con.execute("SELECT pg_advisory_lock(%s)", [MIGRATION_LOCK])
            try:
                self._con.execute(
                    "CREATE TABLE IF NOT EXISTS schema_version (version INTEGER NOT NULL)"
                )
                current = self.scalar("SELECT max(version) FROM schema_version") or 0
                for version, sql in enumerate(MIGRATIONS[current:], start=current + 1):
                    with self.transaction():
                        self._con.execute(sql)
                        self.execute("INSERT INTO schema_version VALUES (?)", [version])
            finally:
                self._con.execute("SELECT pg_advisory_unlock(%s)", [MIGRATION_LOCK])

    @contextmanager
    def transaction(self) -> Iterator[None]:
        """Run a block atomically. Nested use joins the outer transaction.

        Yields:
            Nothing; the block runs inside the transaction and is rolled back if it raises.
        """
        with self._lock:
            # Only the thread holding the lock touches _depth, so a plain attribute is safe.
            self._depth += 1
            try:
                if self._depth > 1:
                    yield
                    return
                self._run("BEGIN")
                try:
                    yield
                except BaseException:
                    if not self._con.closed:
                        self._run("ROLLBACK")
                    raise
                self._run("COMMIT")
            finally:
                self._depth -= 1

    def _run(self, sql: str, params: list[Any] | None = None) -> psycopg.Cursor:
        """Execute one statement.

        When the connection is lost (the database restarted), a statement outside a transaction is
        sent once more on a new connection. Inside a transaction the error is raised (the work so
        far is lost) and the next statement gets a new connection.

        Args:
            sql: SQL statement with ``?`` placeholders.
            params: Positional query parameters.

        Returns:
            The cursor, ready to fetch results.
        """
        # Without parameters psycopg sends the text as it is, so only convert when there are some.
        query = to_psycopg(sql) if params else sql
        params = params or None
        try:
            return self._con.execute(query, params)
        except psycopg.OperationalError:
            if not self._con.closed:
                raise
            log.warning("Lost the database connection; connecting again")
            self._con = self._connect()
            if self._depth:
                raise
            return self._con.execute(query, params)

    def execute(self, sql: str, params: list[Any] | None = None) -> None:
        """Run a statement that returns no rows.

        Args:
            sql: SQL statement.
            params: Positional query parameters.
        """
        with self._lock:
            self._run(sql, params)

    def all(self, sql: str, params: list[Any] | None = None) -> list[dict[str, Any]]:
        """Run a query and return every row as a dict.

        Args:
            sql: SQL query.
            params: Positional query parameters.

        Returns:
            The rows, as column-name dicts.
        """
        with self._lock:
            return self._run(sql, params).fetchall()

    def one(self, sql: str, params: list[Any] | None = None) -> dict[str, Any] | None:
        """Run a query and return its first row as a dict.

        Args:
            sql: SQL query.
            params: Positional query parameters.

        Returns:
            The first row, or None if there are no rows.
        """
        with self._lock:
            return self._run(sql, params).fetchone()

    def scalar(self, sql: str, params: list[Any] | None = None) -> Any:
        """Run a query and return the first column of its first row.

        Args:
            sql: SQL query.
            params: Positional query parameters.

        Returns:
            The value, or None if there are no rows.
        """
        with self._lock:
            row = self._run(sql, params).fetchone()
            return next(iter(row.values())) if row else None

    # --- small helpers used across modules -------------------------------------------------

    def next_counter(self, name: str) -> int:
        """Return the next value (1, 2, …) of a never-reused counter.

        Args:
            name: Counter name.

        Returns:
            The new counter value.
        """
        with self.transaction():
            value = self.scalar("SELECT value FROM counters WHERE name = ?", [name])
            if value is None:
                value = 1
                self.execute("INSERT INTO counters VALUES (?, ?)", [name, value])
            else:
                value += 1
                self.execute("UPDATE counters SET value = ? WHERE name = ?", [value, name])
            return value

    def get_setting(self, key: str, default: str | None = None) -> str | None:
        """Return a stored setting.

        Args:
            key: Setting name.
            default: Value returned when the setting is not stored.

        Returns:
            The stored value, or ``default``.
        """
        value = self.scalar("SELECT value FROM settings WHERE key = ?", [key])
        return default if value is None else value

    def set_setting(self, key: str, value: str) -> None:
        """Store a setting, replacing any existing value.

        Args:
            key: Setting name.
            value: New value.
        """
        self.execute(
            "INSERT INTO settings VALUES (?, ?) "
            "ON CONFLICT (key) DO UPDATE SET value = excluded.value",
            [key, value],
        )

    def audit(self, actor: str, action: str, target: str = "", detail: str = "") -> None:
        """Append an entry to the audit log.

        Args:
            actor: Who performed the action.
            action: What was done.
            target: What it was done to.
            detail: Free-form extra detail.
        """
        self.execute(
            "INSERT INTO audit (actor, action, target, detail) VALUES (?, ?, ?, ?)",
            [actor, action, target, detail],
        )
